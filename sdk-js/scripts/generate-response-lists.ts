// Regenerates src/response-lists.generated.ts from contract-fixtures/api after `just sync-api-contract`.
// Run: pnpm -C sdk-js run generate:response-lists
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildResponseListTables } from "../src/response-lists.test-helper.ts";

const target = fileURLToPath(new URL("../src/response-lists.generated.ts", import.meta.url));
const tables = buildResponseListTables(new URL("../../contract-fixtures/api/", import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/generate-response-lists.ts from contract-fixtures/api. Do not edit.
import type { ResponseListTable } from "./response-lists.js";

/** List fields of the Custd API responses CustdClient decodes. */
export const API_RESPONSE_LISTS: ResponseListTable = ${JSON.stringify(tables.api)};

/** List fields of the app responses AppItemsClient decodes. */
export const APP_RESPONSE_LISTS: ResponseListTable = ${JSON.stringify(tables.app)};

/** List fields of the site config fetchBrowserSiteConfig decodes. */
export const SITE_CONFIG_RESPONSE_LISTS: ResponseListTable = ${JSON.stringify(tables.siteConfig)};
`,
);
execFileSync("pnpm", ["exec", "biome", "format", "--write", target], { stdio: "inherit" });
